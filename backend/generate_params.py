"""Generate the fixed ordinary and bimodal LaZer profiles using exact integers."""
from decimal import Decimal, localcontext
from fractions import Fraction
from math import prod
from pathlib import Path


def generate():
    q = 1151179879138398721
    primes = [1125899906840833, 1125899906839937, 1125899906837633]
    crt = prod(primes)
    assert crt > (q - 1) ** 2 * 64 * 128
    gamma, rows, m1, m2, large = 512, 20, 23, 95, 17
    m = (q - 1) // gamma
    assert (q - 1) % gamma == 0
    sigma1, sigma1_bimodal, sigma2 = (Fraction(31 * 2**exponent, 20)
                                     for exponent in (18, 14, 15))
    assert int(2*m1*64*sigma1**2) == 486050110174658
    assert int(2*m1*64*sigma1_bimodal**2) == 1898633242869
    with localcontext() as ctx:
        ctx.prec = 100
        b = Decimal(sigma2.numerator) / Decimal(sigma2.denominator) * Decimal(2*m2*64).sqrt()
        b += Decimal(504) / 2 * Decimal(rows*64).sqrt()
        b += Decimal(gamma) / 2 * Decimal(rows*64).sqrt()
        bsq = int(b*b)
    assert bsq == 31572639091752
    # Recovered z22 has rows*d centered-Q coefficients. Its raw norm could
    # need 129 bits, so the verifier checks each squared coefficient first.
    assert (((q-1)//2)**2).bit_length() <= 128
    assert (rows*64*((q-1)//2)**2).bit_length() == 129
    assert m2*64*bsq < 2**128  # safe after individual coefficient guards
    values = {"q": q, "qminus1": q-1, "m": m, "mby2": 0 if m%2 else m//2,
              "gamma": gamma, "gammaby2": gamma//2, "pow2D": 1,
              "pow2Dby2": 0, "Bsq": bsq, "scM1": 4*2**128,
              "scM2": 2*2**128, "scM1bimodal": 2*2**128,
              "stdev1sq": round(sigma1*sigma1),
              "stdev1sqbimodal": round(sigma1_bimodal*sigma1_bimodal),
              "stdev2sq": round(sigma2*sigma2), "inv2": -(q-1)//2}
    centered = lambda z: z-q if z > (q-1)//2 else z
    values["Pmodq"] = centered(crt % q)
    for i, prime in enumerate(primes):
        values[f"Ppmodq_{i}"] = centered((crt//prime) % q)
    out = ['/* Generated by backend/generate_params.py. Native sampler variances are',
           ' * rounded backend compatibility fields; research callbacks use exact widths. */',
           '#include "lazer.h"']
    for key, value in values.items():
        nlimbs = 2 if key == "Bsq" or key.startswith("stdev") else max(1, (abs(value).bit_length()+63)//64)
        limbs = [(abs(value) >> (64*i)) & (2**64-1) for i in range(nlimbs)]
        out.append(f'static const limb_t blrs_{key}_limbs[] = {{{", ".join(str(x)+"UL" for x in limbs)}}};')
        out.append(f'static const int_t blrs_{key} = {{{{(limb_t *)blrs_{key}_limbs, {nlimbs}, {int(value<0)}}}}};')
    out += ['static const int_srcptr blrs_Ppmodq[] = {blrs_Ppmodq_0, blrs_Ppmodq_1, blrs_Ppmodq_2};',
            'static const polyring_t blrs_ring = {{blrs_q, 64, 60, 6, moduli_d64, 3, blrs_Pmodq, blrs_Ppmodq, blrs_inv2}};',
            f'static const dcompress_params_t blrs_dcomp = {{{{blrs_q, blrs_qminus1, blrs_m, blrs_mby2, blrs_gamma, blrs_gammaby2, blrs_pow2D, blrs_pow2Dby2, 0, {m%2}, {m.bit_length()}}}}};']
    for label, l, ext in (("quad_eval", large, 6), ("quad_many", large+5, 1)):
        out.append(f'static const abdlop_params_t blrs_{label} = {{{{blrs_ring, blrs_dcomp, {m1}, {m2}, {l}, {ext}, {rows}, blrs_Bsq, 1, 8, 5, 504, 1, 18, blrs_scM1, blrs_stdev1sq, 2, 15, blrs_scM2, blrs_stdev2sq}}}};')
    out += ['static const lnp_quad_eval_params_t blrs_params = {{blrs_quad_eval, blrs_quad_many, 10}};']
    for label, l, ext in (("quad_eval", large, 6), ("quad_many", large+5, 1)):
        out.append(f'static const abdlop_params_t blrs_bimodal_{label} = {{{{blrs_ring, blrs_dcomp, {m1}, {m2}, {l}, {ext}, {rows}, blrs_Bsq, 1, 8, 5, 504, 2, 14, blrs_scM1bimodal, blrs_stdev1sqbimodal, 2, 15, blrs_scM2, blrs_stdev2sq}}}};')
    out += ['static const lnp_quad_eval_params_t blrs_bimodal_params = {{blrs_bimodal_quad_eval, blrs_bimodal_quad_many, 10}};', '']
    return '\n'.join(out)


if __name__ == '__main__':
    target = Path(__file__).with_name('proof_params.h')
    target.write_text(generate(), encoding='ascii')
    print(target)
